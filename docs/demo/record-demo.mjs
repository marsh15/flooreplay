import { chromium } from '../../frontend/node_modules/@playwright/test/index.mjs'
import { randomUUID } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'

const url = process.env.E2E_BASE_URL ?? 'http://localhost:5174'
const api = (process.env.E2E_API_BASE ?? 'http://localhost:8001').replace(/\/api\/v1\/?$/, '')
const username = process.env.E2E_USERNAME
const password = process.env.E2E_PASSWORD
if (!username || !password) throw new Error('Provide a disposable owner via E2E_USERNAME/E2E_PASSWORD.')
await mkdir('docs/demo', { recursive: true })
const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, recordVideo: { dir: 'docs/demo', size: { width: 1440, height: 1000 } } })
const page = await context.newPage()
const pause = () => page.waitForTimeout(1600)
await page.goto(`${url}/incidents/INC-001?revision=2`)
await page.getByRole('heading', { name: 'Observed situation' }).waitFor()
await pause()
await page.getByRole('button', { name: 'Sign in', exact: true }).click()
await page.getByLabel('Username').fill(username)
await page.getByLabel('Password').fill(password)
await page.getByRole('button', { name: 'Continue', exact: true }).click()
await page.getByRole('button', { name: 'Sign out', exact: true }).waitFor()
await pause()
await page.getByLabel('Evidence revision').selectOption('1')
await page.getByText('73', { exact: true }).first().waitFor()
await pause()
await page.getByRole('button', { name: 'EV-MAT-1', exact: true }).first().click()
await page.getByRole('heading', { name: 'Source evidence' }).waitFor()
await pause()
await page.keyboard.press('Escape')
await page.getByLabel('Evidence revision').selectOption('2')
await page.getByText('74', { exact: true }).first().waitFor()
await pause()
const response = await page.request.post(`${api}/api/v1/incidents/INC-001/analyses`, { data: { revision: 2, idempotency_key: randomUUID() } })
if (!response.ok()) throw new Error(`Fresh analysis failed: ${response.status()}`)
const report = await response.json()
await page.evaluate((path) => { history.pushState({}, '', path); window.dispatchEvent(new PopStateEvent('popstate')) }, `/incidents/INC-001?revision=2&analysis=${encodeURIComponent(report.id)}`)
const submit = page.getByRole('button', { name: 'Submit for review' }).first()
await submit.waitFor()
await submit.scrollIntoViewIfNeeded()
await pause()
await submit.click()
const review = page.getByRole('button', { name: 'Record review' }).first()
await review.waitFor()
await review.click()
await page.getByLabel('Review rationale').first().fill('Synthetic demonstration: cited evidence checked; confirm material readiness before any operational change.')
await pause()
await page.getByRole('button', { name: 'Approve review' }).first().click()
await page.getByText('Review recorded. No factory action was executed.').first().waitFor()
await pause()
await page.getByRole('heading', { name: 'OpenAI draft', exact: true }).scrollIntoViewIfNeeded()
await page.getByRole('button', { name: 'Generate draft' }).waitFor()
await page.getByText(/missing api configuration/).waitFor()
await pause()
if (!await page.getByRole('button', { name: 'Generate draft' }).isDisabled()) throw new Error('Recording requires provider generation disabled; do not initiate paid calls.')
await page.evaluate(() => window.scrollTo(0, 0))
await page.screenshot({ path: 'docs/demo/incident-workbench.png', fullPage: false })
await page.goto(`${url}/evaluation`)
await page.getByRole('heading', { name: 'Release dataset integrity' }).waitFor()
await page.getByText('60 / 60', { exact: true }).waitFor()
await pause()
await page.screenshot({ path: 'docs/demo/evaluation.png', fullPage: false })
const video = page.video()
await context.close()
await video.saveAs('docs/demo/flooreplay-local-demo.webm')
await video.delete()
await browser.close()
await writeFile('docs/demo/recording-manifest.json', JSON.stringify({ recorded_at: new Date().toISOString(), api_origin: api, frontend_origin: url, incident_id: 'INC-001', analysis_id: report.id, revision: 2, knowledge_cutoff: report.cutoff, workflow: ['deterministic analysis', 'revision switch', 'source evidence', 'authenticated proposal submission', 'authenticated approval', 'OpenAI unavailable', 'release dataset integrity'], paid_calls: 0, historical_model: 'Qwen archive; not current OpenAI evaluation', limitations: ['Synthetic data', 'No actual OpenAI generation or embeddings verified', 'No independent semantic support review', 'No hosted deployment smoke test'] }, null, 2) + '\n')
console.log('Recorded deterministic incident, authenticated human review, provider-unavailable state and release integrity. No paid calls.')
